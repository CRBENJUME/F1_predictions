import os
import numpy as np
import pandas as pd
import fastf1
from sklearn.ensemble import GradientBoostingRegressor
from sklearn.metrics import mean_absolute_error

# ==========================================
# CONFIGURATION
# ==========================================
TARGET_YEAR = 2025  # Year to predict (or historical year to test accuracy)
TARGET_GP = 'Italian Grand Prix' # Grand Prix name or round
TARGET_SESSION = 'R' # 'R' for Race

# Setup local cache for FastF1 to speed up data loading and prevent API throttling
CACHE_DIR = './f1_cache'
os.makedirs(CACHE_DIR, exist_ok=True)
fastf1.Cache.enable_cache(CACHE_DIR)

def fetch_race_data(year, gp_name):
    """Loads session results and laps for a given year and Grand Prix."""
    print(f"-> Loading session data for {year} {gp_name}...")
    try:
        session = fastf1.get_session(year, gp_name, TARGET_SESSION)
        session.load(telemetry=False, weather=False)
        return session
    except Exception as e:
        print(f"Error loading {year} {gp_name}: {e}")
        return None

def build_features_and_target(session):
    """Extracts features (Grid Position, Qualifying Time delta) and target (Race Time in seconds)."""
    results = session.results.copy()
    laps = session.laps.copy()

    if results.empty or laps.empty:
        return pd.DataFrame()

    # Get the pole position time or driver's personal best quali time as baseline feature
    # FastF1 results usually have 'Q1', 'Q2', 'Q3' or 'Time' (race time)
    # Let's map driver lap times from laps data for accurate race time calculation

    race_times = []
    for driver_num in results['DriverNumber']:
        driver_laps = laps.pick_driver(driver_num)
        valid_laps = driver_laps.pick_accurate()

        if not valid_laps.empty:
            # Total race time in seconds
            total_time = valid_laps['Time'].max().total_seconds()

            # Fast lap / Pace feature (median clean lap time)
            median_lap = valid_laps['LapTime'].dt.total_seconds().median()
        else:
            total_time = np.nan
            median_lap = np.nan

        race_times.append({'DriverNumber': driver_num, 'TotalRaceTime': total_time, 'MedianLapTime': median_lap})

    df_times = pd.DataFrame(race_times)
    df = pd.merge(results, df_times, on='DriverNumber', how='left')

    # Feature cleaning
    df['GridPosition'] = pd.to_numeric(df['GridPosition'], errors='coerce')
    df['TotalRaceTime'] = pd.to_numeric(df['TotalRaceTime'], errors='coerce')
    df['MedianLapTime'] = pd.to_numeric(df['MedianLapTime'], errors='coerce')

    # Filter out drivers who didn't start or complete a meaningful race distance (DNF/DNS)
    df = df.dropna(subset=['TotalRaceTime', 'GridPosition', 'MedianLapTime'])
    return df

def main():
    print("==================================================")
    print(f" F1 Gradient Boosting Predictor ({TARGET_YEAR} - {TARGET_GP})")
    print("==================================================")

    # 1. Gather Historical Training Data (e.g., previous races from 2024 / early 2025)
    # To keep training robust, we aggregate a few rounds as historical context
    training_gps = ['Bahrain Grand Prix', 'Saudi Arabian Grand Prix', 'Australian Grand Prix', 'Monaco Grand Prix']
    training_data_list = []

    print("\n[1/4] Pulling historical data for training model...")
    for gp in training_gps:
        try:
            hist_session = fetch_race_data(2024, gp)
            if hist_session:
                df_hist = build_features_and_target(hist_session)
                if not df_hist.empty:
                    training_data_list.append(df_hist)
        except Exception:
            continue

    if not training_data_list:
        print("Warning: Could not load multi-race history, falling back to current target event split.")

    # Combine training data
    if training_data_list:
        train_df = pd.concat(training_data_list, ignore_index=True)
    else:
        # Fallback dummy collection if historical requests fail
        target_session_obj = fetch_race_data(TARGET_YEAR, TARGET_GP)
        train_df = build_features_and_target(target_session_obj)

    # Features to use: Grid Position and Median Clean Lap Time proxy
    features = ['GridPosition', 'MedianLapTime']
    target = 'TotalRaceTime'

    train_df = train_df.dropna(subset=features + [target])

    X_train = train_df[features]
    y_train = train_df[target]

    # 2. Train Gradient Boosting Regressor
    print("\n[2/4] Training Gradient Boosting Regressor model...")
    model = GradientBoostingRegressor(n_estimators=100, learning_rate=0.1, max_depth=3, random_state=42)
    model.fit(X_train, y_train)

    # 3. Pull Target Race Data for Prediction & Evaluation
    print(f"\n[3/4] Pulling target data for {TARGET_YEAR} {TARGET_GP}...")
    target_session = fetch_race_data(TARGET_YEAR, TARGET_GP)
    if target_session is None or target_session.results.empty:
        print("Could not retrieve target session data. Check GP name or year.")
        return

    test_df = build_features_and_target(target_session)
    if test_df.empty:
        print("Not enough completed laps/results found for evaluation.")
        return

    X_test = test_df[features]
    y_test = test_df[target]

    # 4. Predict & Evaluate with Mean Absolute Error (MAE)
    print("\n[4/4] Generating predictions and evaluating accuracy...")
    predictions = model.predict(X_test)
    test_df['PredictedRaceTime'] = predictions

    # Calculate MAE in seconds
    mae = mean_absolute_error(y_test, predictions)

    # Sort drivers by predicted finishing time
    test_df = test_df.sort_values(by='PredictedRaceTime').reset_index(drop=True)

    # Format output display
    print("\n==================================================")
    print(f" PREDICTED FINISHING ORDER: {TARGET_YEAR} {TARGET_GP}")
    print("==================================================")
    print(f"{'Pos':<4} | {'Driver':<20} | {'Team':<15} | {'Grid':<6} | {'Pred Time (s)':<14}")
    print("-" * 68)

    for idx, row in test_df.iterrows():
        pos = idx + 1
        driver_name = f"{row['FirstName']} {row['LastName']}"
        team_name = row['TeamName']
        grid = int(row['GridPosition'])
        pred_time = f"{row['PredictedRaceTime']:.3f}s"
        print(f"{pos:<4} | {driver_name:<20} | {team_name:<15} | {grid:<6} | {pred_time:<14}")

    print("-" * 68)
    print(f"Model Evaluation -> Mean Absolute Error (MAE): {mae:.3f} seconds")
    print("==================================================")

if __name__ == '__main__':
    main()